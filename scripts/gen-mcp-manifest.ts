/**
 * Generates lib/mcp/route-manifest.ts — the list of /api routes (and the HTTP
 * methods each exports) that the MCP server's `list_api_routes` tool describes.
 *
 * Vercel's serverless runtime cannot glob app/api at request time, so the list is
 * generated here and committed. tests/mcp-manifest.test.ts re-scans the tree and
 * fails if the committed file is stale, so a new route cannot quietly be missing
 * from what an AI client is told exists.
 *
 *   npm run mcp:manifest
 */
import { readdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";

export type ManifestRoute = { path: string; methods: string[]; params?: string[]; body?: string[] };

const METHOD_RE = /export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE)\b|export\s+const\s+(GET|POST|PUT|PATCH|DELETE)\s*=/g;
// The query-string parameters a route reads. The receiver name is restricted to
// the ones this codebase uses for a URLSearchParams, so headers.get("…") and
// cookies.get("…") are not mistaken for parameters. The first live user found
// that `asOf` was required only by getting a 400 — this is what tells them first.
const PARAM_RE = /\b(?:searchParams|sp|params|qs|query|q|url\.searchParams)\.get(?:All)?\(\s*["'`]([A-Za-z0-9_.-]{1,40})["'`]\s*\)/g;

// ── Request-body field names ─────────────────────────────────────────────────
// A model told only "POST /api/invoices/[id]/promises" has to guess the body.
// Names are taken from two places, both read out of the route's own source:
// the keys of any `z.object({ … })` schema, and `body.x` / `b.x` reads. They are
// names, never a promise that each is required or what type it takes.
const BODY_READ_RE = /\b(?:body|b|payload|input)\.([A-Za-z_][A-Za-z0-9_]{0,40})\b/g;
const NOT_FIELDS = new Set([
  "json", "length", "map", "filter", "forEach", "trim", "toString", "slice", "some", "every", "includes", "hasOwnProperty", "push", "split",
  "join", "keys", "values", "entries", "find", "reduce", "sort", "concat", "startsWith", "endsWith", "toLowerCase", "toUpperCase", "replace",
  "match", "test", "exec", "then", "catch", "finally", "success", "error", "issues", "flatten", "data", "text", "ok", "status",
]);
const MAX_BODY_FIELDS = 24;

/** The top-level keys of the object literal that starts right after `openIndex` (the index of its `{`). */
function topLevelKeys(src: string, openIndex: number): string[] {
  const keys: string[] = [];
  let depth = 0;
  let seg = "";
  const flush = () => {
    const m = /^\s*(?:\/\/[^\n]*\n\s*)*([A-Za-z_][A-Za-z0-9_]*)\s*:/.exec(seg);
    if (m) keys.push(m[1]);
    seg = "";
  };
  for (let i = openIndex + 1; i < src.length; i++) {
    const ch = src[i];
    if (ch === "{" || ch === "[" || ch === "(") depth++;
    else if (ch === "}" || ch === "]" || ch === ")") {
      if (depth === 0) { flush(); break; }
      depth--;
    } else if (ch === "," && depth === 0) { flush(); continue; }
    seg += ch;
  }
  return keys;
}

export function bodyFieldsOf(src: string): string[] {
  const names = new Set<string>();
  for (const m of src.matchAll(/z\.object\(\s*\{/g)) for (const k of topLevelKeys(src, (m.index ?? 0) + m[0].length - 1)) names.add(k);
  for (const m of src.matchAll(BODY_READ_RE)) if (!NOT_FIELDS.has(m[1])) names.add(m[1]);
  return [...names].sort().slice(0, MAX_BODY_FIELDS);
}

function walk(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, out);
    else if (e.name === "route.ts" || e.name === "route.tsx") out.push(full);
  }
  return out;
}

export function scanApiRoutes(root: string = path.join(process.cwd(), "app", "api")): ManifestRoute[] {
  const routes: ManifestRoute[] = [];
  for (const file of walk(root)) {
    const methods = new Set<string>();
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(METHOD_RE)) methods.add(m[1] ?? m[2]);
    if (methods.size === 0) continue;
    const params = [...new Set([...src.matchAll(PARAM_RE)].map((m) => m[1]))].sort();
    const rel = path.relative(root, path.dirname(file)).split(path.sep).filter((s) => !/^\(.*\)$/.test(s));
    const writes = [...methods].some((m) => m === "POST" || m === "PUT" || m === "PATCH");
    const body = writes ? bodyFieldsOf(src).filter((f) => !params.includes(f)) : [];
    routes.push({ path: "/api" + (rel.length ? "/" + rel.join("/") : ""), methods: [...methods].sort(), ...(params.length ? { params } : {}), ...(body.length ? { body } : {}) });
  }
  return routes.sort((a, b) => a.path.localeCompare(b.path));
}

export function renderManifest(routes: ManifestRoute[]): string {
  const rows = routes.map((r) =>
    `  { path: ${JSON.stringify(r.path)}, methods: ${JSON.stringify(r.methods)}${r.params ? `, params: ${JSON.stringify(r.params)}` : ""}${r.body ? `, body: ${JSON.stringify(r.body)}` : ""} },`,
  ).join("\n");
  return `// GENERATED by scripts/gen-mcp-manifest.ts — do not edit by hand. Run: npm run mcp:manifest
export const API_ROUTES: readonly { path: string; methods: readonly string[]; params?: readonly string[]; body?: readonly string[] }[] = [
${rows}
];
`;
}

if (process.argv[1] && /gen-mcp-manifest\.ts$/.test(process.argv[1])) {
  const routes = scanApiRoutes();
  writeFileSync(path.join(process.cwd(), "lib", "mcp", "route-manifest.ts"), renderManifest(routes));
  console.log(`wrote lib/mcp/route-manifest.ts — ${routes.length} routes`);
}
