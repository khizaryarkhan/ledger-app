/**
 * Generates lib/mcp/route-manifest.ts — the list of /api routes (and the HTTP
 * methods each exports) that the MCP server's `list_api_routes` tool describes.
 *
 * Vercel's serverless runtime cannot glob app/api at request time, so the list is
 * generated here and committed. tests/mcp-manifest.test.ts re-scans the tree and
 * fails if the committed file is stale, so a new route cannot quietly be missing
 * from what an AI client is told exists.
 *
 *   npm run mcp:manifest
 */
import { readdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";

export type ManifestRoute = { path: string; methods: string[] };

const METHOD_RE = /export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE)\b|export\s+const\s+(GET|POST|PUT|PATCH|DELETE)\s*=/g;

function walk(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, out);
    else if (e.name === "route.ts" || e.name === "route.tsx") out.push(full);
  }
  return out;
}

export function scanApiRoutes(root: string = path.join(process.cwd(), "app", "api")): ManifestRoute[] {
  const routes: ManifestRoute[] = [];
  for (const file of walk(root)) {
    const methods = new Set<string>();
    for (const m of readFileSync(file, "utf8").matchAll(METHOD_RE)) methods.add(m[1] ?? m[2]);
    if (methods.size === 0) continue;
    const rel = path.relative(root, path.dirname(file)).split(path.sep).filter((s) => !/^\(.*\)$/.test(s));
    routes.push({ path: "/api" + (rel.length ? "/" + rel.join("/") : ""), methods: [...methods].sort() });
  }
  return routes.sort((a, b) => a.path.localeCompare(b.path));
}

export function renderManifest(routes: ManifestRoute[]): string {
  const rows = routes.map((r) => `  { path: ${JSON.stringify(r.path)}, methods: ${JSON.stringify(r.methods)} },`).join("\n");
  return `// GENERATED by scripts/gen-mcp-manifest.ts — do not edit by hand. Run: npm run mcp:manifest
export const API_ROUTES: readonly { path: string; methods: readonly string[] }[] = [
${rows}
];
`;
}

if (process.argv[1] && /gen-mcp-manifest\.ts$/.test(process.argv[1])) {
  const routes = scanApiRoutes();
  writeFileSync(path.join(process.cwd(), "lib", "mcp", "route-manifest.ts"), renderManifest(routes));
  console.log(`wrote lib/mcp/route-manifest.ts — ${routes.length} routes`);
}
